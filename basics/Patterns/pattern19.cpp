/*===================================== Pattern 12 ==================================================

**********              |````/\````|
****  ****              | 1 /  \ 3 |
***    ***              |  / 2  \  |
**      **              | /      \ |
*        *  -----\      |/________\|          
*        *  -----/      |\        /| 
**      **              | \  5   / |
***    ***              |  \    /  |
****  ****              | 4 \  / 6 |
**********              |____\/____|

===================================================================================================*/

#include<iostream>
using namespace std;

int main(){

    for(int i = 0; i<5; i++){           // 1
        for (int j = 0; j < 5-i; j++){
            cout<<"*";
        }
        for (int j = 0; j <2*i; j++){  //2
            cout<<" ";
        }
        for (int j = 0; j < 5-i; j++){ //3
            cout<<"*";
        }
        cout<<'\n';
    }
    for(int i = 0; i<5; i++){           //4
        for (int j = 0; j <i+1; j++){
            cout<<"*";
        }
        for (int j = 0; j <2*(4-i); j++){   //5
            cout<<" ";
        }
        for (int j = 0; j < i+1; j++){     //6
            cout<<"*";
        }
        cout<<'\n';
    }

    return 0;
}